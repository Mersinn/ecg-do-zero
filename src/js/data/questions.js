/** Agrupa os ids das questões por família diagnóstica. */
export const questoesPorFamilia = () => {
  const mapa = {};
  for (const q of QUESTOES) (mapa[q.familia] ||= []).push(q.id);
  return mapa;
};

/** Questões que se apoiam em um traçado sintetizado pela biblioteca de padrões. */
export const questoesComTracado = () => QUESTOES.filter((q) => q.padrao !== null);

/** Busca por id, para retomar uma questão a partir da fila de revisão. */
export const acharQuestao = (id) => QUESTOES.find((q) => q.id === id) || null;
